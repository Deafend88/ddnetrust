"""Generates rust-client/client/src/tolower.rs from the C++ table
src/base/unicode/tolower_data.cpp (`str_utf8_tolower_codepoint`), sorted for a binary search.

Usage: python rust-client/scripts/gen_tolower.py
"""

import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "src", "base", "unicode", "tolower_data.cpp")
OUT = os.path.join(ROOT, "rust-client", "client", "src", "tolower.rs")

with open(SRC, encoding="utf-8") as f:
	pairs = sorted((int(a), int(b)) for a, b in re.findall(r"\{(\d+), (\d+)\}", f.read()))

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
	f.write("//! Generated by scripts/gen_tolower.py from src/base/unicode/tolower_data.cpp. Do not\n")
	f.write("//! edit.\n\n")
	f.write("/// C++ `UPPER_TO_LOWER_CODEPOINT_MAP`, sorted by the upper case code point.\n")
	f.write(f"const MAP: [(i32, i32); {len(pairs)}] = [\n")
	for a, b in pairs:
		f.write(f"    ({a}, {b}),\n")
	f.write("];\n\n")
	f.write("/// C++: `str_utf8_tolower_codepoint`.\n")
	f.write("pub fn tolower(code: i32) -> i32 {\n")
	f.write("    MAP.binary_search_by_key(&code, |p| p.0)\n")
	f.write("        .map_or(code, |i| MAP[i].1)\n")
	f.write("}\n")
print(f"{len(pairs)} pairs -> {OUT}")
