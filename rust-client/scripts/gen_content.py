"""Generates rust-client/client/src/render/content.rs from datasrc/content.py.

The C++ side generates src/generated/client_data.{h,cpp} from the same file with
datasrc/compile.py; this script emits the parts the Rust renderer uses: sprite sets,
sprites, animations and weapon specs, with the same names and indices as the C++
enums (SPRITE_*, ANIM_*). Floats are written like datatypes.Float ("{:f}"), so they
round to the same f32 as the C++ literals.

Run from anywhere: python rust-client/scripts/gen_content.py
"""

import os
import subprocess
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "datasrc"))

import content  # noqa: E402

OUT = os.path.join(ROOT, "rust-client", "client", "src", "render", "content.rs")


def f32(v):
	return f"{v:f}"


def main():
	c = content.container
	sets = c.spritesets.items
	sprites = c.sprites.items
	anims = c.animations.items
	out = [
		"//! Generated by `scripts/gen_content.py` from `datasrc/content.py`. Do not edit.",
		"//! C++: `src/generated/client_data.{h,cpp}` (sprite sets, sprites, animations,",
		"//! weapon specs), same order and names.",
		"",
		"// floats are written like the C++ literals",
		"#![allow(clippy::excessive_precision)]",
		"",
		"#[derive(Clone, Copy, Debug)]",
		"pub struct SpriteSet {",
		"    pub name: &'static str,",
		"    pub gridx: i32,",
		"    pub gridy: i32,",
		"}",
		"",
		"#[derive(Clone, Copy, Debug)]",
		"pub struct Sprite {",
		"    pub name: &'static str,",
		"    pub set: usize,",
		"    pub x: i32,",
		"    pub y: i32,",
		"    pub w: i32,",
		"    pub h: i32,",
		"}",
		"",
		"/// C++: `CAnimKeyframe`.",
		"#[derive(Clone, Copy, Debug, Default, PartialEq)]",
		"pub struct Keyframe {",
		"    pub time: f32,",
		"    pub x: f32,",
		"    pub y: f32,",
		"    pub angle: f32,",
		"}",
		"",
		"/// C++: `CAnimation`.",
		"#[derive(Clone, Copy, Debug)]",
		"pub struct Animation {",
		"    pub name: &'static str,",
		"    pub body: &'static [Keyframe],",
		"    pub back_foot: &'static [Keyframe],",
		"    pub front_foot: &'static [Keyframe],",
		"    pub attach: &'static [Keyframe],",
		"}",
		"",
		"/// C++: `CDataWeaponspec` (the fields the renderer reads).",
		"#[derive(Clone, Copy, Debug)]",
		"pub struct WeaponSpec {",
		"    pub name: &'static str,",
		"    pub sprite_body: usize,",
		"    pub visual_size: i32,",
		"    pub offsetx: f32,",
		"    pub offsety: f32,",
		"}",
		"",
	]
	out.append(f"pub const SPRITESETS: [SpriteSet; {len(sets)}] = [")
	for s in sets:
		out.append(f'    SpriteSet {{ name: "{s.image.target.name.value}", gridx: {s.gridx.value}, gridy: {s.gridy.value} }},')
	out.append("];")
	out.append("")
	for i, s in enumerate(sprites):
		out.append(f"pub const SPRITE_{s.name.value.upper()}: usize = {i};")
	out.append(f"pub const SPRITES: [Sprite; {len(sprites)}] = [")
	for s in sprites:
		out.append(f'    Sprite {{ name: "{s.name.value}", set: {sets.index(s.set.target)}, x: {s.x.value}, y: {s.y.value}, w: {s.w.value}, h: {s.h.value} }},')
	out.append("];")
	out.append("")

	def frames(seq):
		return "&[" + ", ".join(f"Keyframe {{ time: {f32(k.time.value)}, x: {f32(k.x.value)}, y: {f32(k.y.value)}, angle: {f32(k.angle.value)} }}" for k in seq.frames.items) + "]"

	for i, a in enumerate(anims):
		out.append(f"pub const ANIM_{a.name.value.upper()}: usize = {i};")
	out.append(f"pub const ANIMATIONS: [Animation; {len(anims)}] = [")
	for a in anims:
		out.append(f'    Animation {{ name: "{a.name.value}", body: {frames(a.body)}, back_foot: {frames(a.back_foot)}, front_foot: {frames(a.front_foot)}, attach: {frames(a.attach)} }},')
	out.append("];")
	out.append("")
	weapons = c.weapons.id.items
	out.append(f"pub const WEAPONS: [WeaponSpec; {len(weapons)}] = [")
	for w in weapons:
		out.append(f'    WeaponSpec {{ name: "{w.name.value}", sprite_body: SPRITE_{w.sprite_body.target.name.value.upper()}, visual_size: {w.visual_size.value}, offsetx: {f32(w.offsetx.value)}, offsety: {f32(w.offsety.value)} }},')
	out.append("];")
	with open(OUT, "w", newline="\n") as f:
		f.write("\n".join(out) + "\n")
	subprocess.run(["rustfmt", "--edition", "2024", OUT], check=True)


if __name__ == "__main__":
	main()
