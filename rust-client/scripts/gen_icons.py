"""Generates rust-client/client/src/icons.rs: codepoints of the Phosphor icons DDNet-rs
uses, read from Phosphor's style.css (npm package @phosphor-icons/web 2.1.2, the
regular weight, same version as rust-client/assets/fonts/Phosphor.ttf).

Usage: python rust-client/scripts/gen_icons.py <path to src/regular/style.css>
Add icon names to ICONS and run it again when a widget needs another icon.
"""

import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "rust-client", "client", "src", "icons.rs")

# Phosphor name -> Rust constant
ICONS = [
	("user", "USER"),
	("fingerprint", "FINGERPRINT"),
	("lightning", "BOLT"),
	("cloud", "CLOUD"),
	("globe", "GLOBE"),
	("clock", "CLOCK"),
	("gauge", "GAUGE"),
	("timer", "TIMER"),
	("pulse", "PULSE"),
	("check-circle", "CHECK_CIRCLE"),
	("trophy", "TROPHY"),
	("flag-checkered", "FLAG_CHECKERED"),
	("skull", "SKULL"),
	("megaphone", "MEGAPHONE"),
	("music-notes", "MUSIC_NOTES"),
	("play", "PLAY"),
	("pause", "PAUSE"),
	("skip-back", "SKIP_BACK"),
	("skip-forward", "SKIP_FORWARD"),
	("dots-three", "DOTS_THREE"),
	("gear", "GEAR"),
	("x", "X"),
	("check", "CHECK"),
	("eye", "EYE"),
	("eye-slash", "EYE_SLASH"),
	("arrows-out-cardinal", "MOVE"),
	("arrow-counter-clockwise", "RESET"),
	("plugs-connected", "CONNECT"),
	("sign-out", "DISCONNECT"),
	("power", "POWER"),
	("play-circle", "PLAY_CIRCLE"),
	("crosshair", "CROSSHAIR"),
	("map-pin", "MAP_PIN"),
	("compass", "COMPASS"),
	("snowflake", "SNOWFLAKE"),
	("rocket", "ROCKET"),
	("link", "LINK"),
	("prohibit", "PROHIBIT"),
	("users", "USERS"),
	("info", "INFO"),
]


def main():
	css = open(sys.argv[1], encoding="utf-8").read()
	codes = dict(re.findall(r'\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css))
	with open(OUT, "w", encoding="utf-8", newline="\n") as f:
		f.write("// Generated by rust-client/scripts/gen_icons.py from Phosphor 2.1.2 (MIT). Do not edit.\n\n")
		f.write("//! Phosphor icon glyphs (draw with the `icons` font family, see `style.rs`).\n\n")
		for name, const in ICONS:
			f.write(f'/// Phosphor `{name}`.\npub const {const}: &str = "\\u{{{codes[name]}}}";\n')
		f.write(f"\n/// Every icon above, in order (the gallery shows them all).\npub const ALL: [&str; {len(ICONS)}] = [\n")
		for _, const in ICONS:
			f.write(f"    {const},\n")
		f.write("];\n")


if __name__ == "__main__":
	main()
