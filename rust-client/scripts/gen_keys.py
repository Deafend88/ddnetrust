"""Generates rust-client/client/src/keynames.rs from src/engine/client/keynames.cpp.

The C++ table (g_aaKeyStrings, itself generated by scripts/gen_keys.py) is copied
verbatim: KeyName(i) is entry i, and CInput::FindKeyByName searches it.

Run from anywhere: python rust-client/scripts/gen_keys.py
"""

import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "src", "engine", "client", "keynames.cpp")
OUT = os.path.join(ROOT, "rust-client", "client", "src", "keynames.rs")


def main():
	with open(SRC, encoding="utf-8") as f:
		names = re.findall(r'^\t"([^"]*)",?$', f.read(), re.M)
	assert len(names) == 512, len(names)
	with open(OUT, "w", encoding="utf-8", newline="\n") as f:
		f.write("// Generated by rust-client/scripts/gen_keys.py from src/engine/client/keynames.cpp.\n")
		f.write("// Do not edit.\n\n")
		f.write("/// C++: `g_aaKeyStrings`: `KeyName(key)` for every key id (SDL scancodes, then\n")
		f.write("/// mouse buttons and wheel, joystick buttons, axes and hats).\n")
		f.write("pub const KEY_NAMES: [&str; 512] = [\n")
		for n in names:
			f.write(f'    "{n}",\n')
		f.write("];\n")


if __name__ == "__main__":
	main()
