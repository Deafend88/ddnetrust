"""Generates rust-client/ddnet/src/protocol/generated.rs from datasrc/network.py.

The C++ side generates src/generated/protocol.{h,cpp} from the same file with
datasrc/compile.py; this script mirrors that output for the Rust client:
enums/flags, object/event/message ids and layouts, range checks, ex UUIDs.

Run from anywhere: python rust-client/scripts/gen_protocol.py
"""

import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "datasrc"))

import content  # noqa: E402
import network  # noqa: E402
from datatypes import NetArray, NetIntAny, NetIntRange, NetString, NetStringHalfStrict, NetStringStrict  # noqa: E402

OUT = os.path.join(ROOT, "rust-client", "ddnet", "src", "protocol", "generated.rs")

# C++ constants used as range bounds in network.py that are not defined there.
CPP_CONSTANTS = {
	"MAX_CLIENTS": 128,  # engine/shared/protocol.h
	"MIN_TICK": 0,  # engine/shared/protocol.h
	"MAX_TICK": 0x6FFFFFFF,  # engine/shared/protocol.h
	"max_int": 0x7FFFFFFF,  # generated protocol.cpp
	"min_int": -0x80000000,  # generated protocol.cpp
	"FinishTime::NOT_FINISHED_MILLIS": -1,  # engine/shared/protocol.h
	"FinishTime::UNSET": -2,  # engine/shared/protocol.h
	"TuneZone::NUM": 256,  # engine/shared/protocol.h
	"TuneZone::OVERRIDE_NONE": -1,  # engine/shared/protocol.h
	"FLAG_MISSING": -3,  # network.RawHeader
	"SPEC_FREEVIEW": -1,  # network.RawHeader
	"WEAPON_GAME": -3,  # compile.py gen_network_header
	"NUM_WEAPONS": len(content.container.weapons.id.items),
	"NUM_SOUNDS": len(content.container.sounds.items),
}

RUST_KEYWORDS = {"type", "self", "mod", "move", "ref", "use", "where", "loop", "match", "box", "in", "fn", "impl", "crate", "super", "struct", "enum", "trait", "dyn", "static", "const", "pub", "let", "mut", "return", "if", "else", "for", "while", "true", "false", "as", "break", "continue", "extern", "unsafe", "async", "await", "abstract", "final", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "macro", "become", "do", "gen"}

TEEWORLDS_NAMESPACE = bytes.fromhex("e05ddaaac4e64cfbb6425d48e80c0029")


def calculate_uuid(name):
	"""C++: CalculateUuid (uuid_manager.cpp)."""
	d = bytearray(hashlib.md5(TEEWORLDS_NAMESPACE + name.encode()).digest())
	d[6] = (d[6] & 0x0F) | 0x30
	d[8] = (d[8] & 0x3F) | 0x80
	return bytes(d)


def rust_bytes(b):
	return "[" + ", ".join(f"0x{x:02x}" for x in b) + "]"


def build_env():
	env = dict(CPP_CONSTANTS)
	for e in network.Enums:
		for i, v in enumerate(e.values):
			env[f"{e.name}_{v}"] = e.start + i
		env[f"NUM_{e.name}S"] = e.start + len(e.values)
	return env


ENV = build_env()


def evaluate(expr):
	"""Evaluates a range bound such as 'MAX_CLIENTS-1' to an int."""
	if isinstance(expr, int):
		return expr
	s = str(expr).strip().strip('"')
	names = sorted(ENV, key=len, reverse=True)
	for name in names:
		s = s.replace(name, f"({ENV[name]})")
	if not re.fullmatch(r"[0-9()+\-* ]+", s):
		raise ValueError(f"cannot evaluate range bound {expr!r} -> {s!r}")
	return int(eval(s))  # only digits and arithmetic remain


def field_name(cpp_name):
	n = re.sub(r"^m_[ap]?(?=[A-Z])", "", cpp_name)
	n = re.sub(r"^m_", "", n)
	n = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", n).lower()
	return n + "_" if n in RUST_KEYWORDS else n


def type_name(name):
	return name.replace("_", "")


def int_fields(variables):
	"""Flattens an object's variables to its int slots: (name, range, default)."""
	out = []
	for v in variables:
		if isinstance(v, NetArray):
			for i in range(v.size):
				out.append((f"{field_name(v.base_name)}[{i}]", v.var, v.var.default))
		else:
			out.append((field_name(v.name), v, v.default))
	return out


def gen():
	lines = [
		"// @generated by rust-client/scripts/gen_protocol.py from datasrc/network.py.",
		"// Do not edit; regenerate instead. Mirrors src/generated/protocol.{h,cpp}.",
		"#![allow(clippy::all, unused_mut, unused_comparisons)]",
		"",
		"use super::packer::{Packer, Unpacker, SANITIZE, SANITIZE_CC, SKIP_START_WHITESPACES};",
		"",
	]

	for e in network.Enums:
		for i, v in enumerate(e.values):
			lines.append(f"pub const {e.name}_{v}: i32 = {e.start + i};")
		lines.append(f"pub const NUM_{e.name}S: i32 = {e.start + len(e.values)};")
	for f in network.Flags:
		for i, v in enumerate(f.values):
			lines.append(f"pub const {f.name}_{v}: i32 = 1 << {i};")
	lines.append(f"pub const NUM_WEAPONS: i32 = {CPP_CONSTANTS['NUM_WEAPONS']};")
	for i, w in enumerate(content.container.weapons.id.items):
		lines.append(f"pub const WEAPON_{w.name.value.upper()}: i32 = {i};")
	lines.append("")

	# --- objects and events ---
	objects = network.Objects
	plain = [o for o in objects if o.ex is None]
	ex = [o for o in objects if o.ex is not None]
	lines.append("pub const NETOBJTYPE_EX: i32 = 0;")
	for i, o in enumerate(plain):
		lines.append(f"pub const {o.enum_name}: i32 = {i + 1};")
	lines.append(f"pub const NUM_NETOBJTYPES: i32 = {len(plain) + 1};")
	lines.append("/// Ids for extended (UUID) object types; local to this client, never sent.")
	lines.append("pub const OFFSET_EX_NETOBJTYPE: i32 = 0x10000;")
	for i, o in enumerate(ex):
		lines.append(f"pub const {o.enum_name}: i32 = OFFSET_EX_NETOBJTYPE + {i};")
	lines.append("")

	lines += [
		"/// One int slot of a snapshot object. C++: generated `CNetObjHandler::SecureUnpackObj`.",
		"pub struct ObjField {",
		"    pub name: &'static str,",
		"    /// Clamped into this range after unpacking (`ClampInt`).",
		"    pub range: Option<(i32, i32)>,",
		"    /// Used when the item ends exactly before this slot (`GetUncompressedIntOrDefault`).",
		"    pub default: Option<i32>,",
		"}",
		"",
		"pub struct ObjSpec {",
		"    pub type_id: i32,",
		"    pub name: &'static str,",
		"    pub uuid: Option<[u8; 16]>,",
		"    pub fields: &'static [ObjField],",
		"}",
		"",
		"pub static OBJ_SPECS: &[ObjSpec] = &[",
	]
	for o in objects:
		uuid = f"Some({rust_bytes(calculate_uuid(o.ex))})" if o.ex else "None"
		lines.append(f"    ObjSpec {{ type_id: {o.enum_name}, name: \"{o.name}\", uuid: {uuid}, fields: &[")
		for name, var, default in int_fields(o.members_from_this_and_parents(objects)):
			rng = f"Some(({evaluate(var.min)}, {evaluate(var.max)}))" if isinstance(var, NetIntRange) else "None"
			dflt = f"Some({evaluate(default)})" if default is not None else "None"
			lines.append(f"        ObjField {{ name: \"{name}\", range: {rng}, default: {dflt} }},")
		lines.append("    ] },")
	lines.append("];")
	lines.append("")

	for o in objects:
		fields = o.members_from_this_and_parents(objects)
		sname = ("Event" if o.enum_name.startswith("NETEVENTTYPE_") else "Obj") + type_name(o.name)
		lines.append(f"/// C++: `{o.struct_name}`.")
		lines.append("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]")
		lines.append(f"pub struct {sname} {{")
		for v in fields:
			t = f"[i32; {v.size}]" if isinstance(v, NetArray) else "i32"
			n = field_name(v.base_name if isinstance(v, NetArray) else v.name)
			lines.append(f"    pub {n}: {t},")
		lines.append("}")
		n_ints = len(int_fields(fields))
		lines.append(f"impl {sname} {{")
		lines.append(f"    pub const TYPE_ID: i32 = {o.enum_name};")
		lines.append(f"    pub const NUM_INTS: usize = {n_ints};")
		lines.append("    pub fn from_ints(d: &[i32]) -> Self {")
		lines.append("        let mut s = Self::default();")
		i = 0
		for v in fields:
			if isinstance(v, NetArray):
				n = field_name(v.base_name)
				lines.append(f"        s.{n}.copy_from_slice(&d[{i}..{i + v.size}]);")
				i += v.size
			else:
				lines.append(f"        s.{field_name(v.name)} = d[{i}];")
				i += 1
		lines.append("        s")
		lines.append("    }")
		lines.append("    pub fn to_ints(&self) -> Vec<i32> {")
		lines.append(f"        let mut d = Vec::with_capacity({n_ints});")
		for v in fields:
			if isinstance(v, NetArray):
				lines.append(f"        d.extend_from_slice(&self.{field_name(v.base_name)});")
			else:
				lines.append(f"        d.push(self.{field_name(v.name)});")
		lines.append("        d")
		lines.append("    }")
		lines.append("}")
		lines.append("")

	# --- messages ---
	messages = network.Messages
	plain = [m for m in messages if m.ex is None]
	ex = [m for m in messages if m.ex is not None]
	lines.append("pub const NETMSGTYPE_EX: i32 = 0;")
	for i, m in enumerate(plain):
		lines.append(f"pub const {m.enum_name}: i32 = {i + 1};")
	lines.append(f"pub const NUM_NETMSGTYPES: i32 = {len(plain) + 1};")
	lines.append("/// Ids for extended (UUID) game messages; local to this client, never sent.")
	lines.append("pub const OFFSET_EX_NETMSGTYPE: i32 = 0x20000;")
	for i, m in enumerate(ex):
		lines.append(f"pub const {m.enum_name}: i32 = OFFSET_EX_NETMSGTYPE + {i};")
	lines.append("")

	lines.append("/// (id, name, uuid) of every game message. Names match C++ `GetMsgName`.")
	lines.append("pub static MSG_TYPES: &[(i32, &str, Option<[u8; 16]>)] = &[")
	for m in messages:
		uuid = f"Some({rust_bytes(calculate_uuid(m.ex))})" if m.ex else "None"
		lines.append(f"    ({m.enum_name}, \"{m.name}\", {uuid}),")
	lines.append("];")
	lines.append("")

	string_flags = {
		NetString: "SANITIZE",
		NetStringHalfStrict: "SANITIZE_CC",
		NetStringStrict: "SANITIZE_CC | SKIP_START_WHITESPACES",
	}

	def msg_slots(m):
		"""(rust field access, var) per wire slot, arrays expanded."""
		out = []
		for v in m.variables:
			if isinstance(v, NetArray):
				for i in range(v.size):
					out.append((f"{field_name(v.base_name)}[{i}]", v.var))
			else:
				out.append((field_name(v.name), v))
		return out

	for m in messages:
		sname = "Msg" + type_name(m.name)
		lines.append(f"/// C++: `{m.struct_name}`.")
		lines.append("#[derive(Clone, Debug, Default, PartialEq, Eq)]")
		lines.append(f"pub struct {sname} {{")
		for v in m.variables:
			base = v.var if isinstance(v, NetArray) else v
			t = "String" if type(base) in string_flags else "i32"
			if isinstance(v, NetArray):
				t = f"[{t}; {v.size}]"
			lines.append(f"    pub {field_name(v.base_name if isinstance(v, NetArray) else v.name)}: {t},")
		lines.append("}")
		lines.append(f"impl {sname} {{")
		lines.append(f"    pub const ID: i32 = {m.enum_name};")
		lines.append("    /// C++: generated `Pack`.")
		lines.append("    pub fn pack(&self, p: &mut Packer) {")
		if not m.variables:
			lines.append("        let _ = p;")
		for acc, var in msg_slots(m):
			if type(var) in string_flags:
				lines.append(f"        p.add_string(self.{acc}.as_bytes(), -1, true);")
			else:
				lines.append(f"        p.add_int(self.{acc});")
		lines.append("    }")
		lines.append("    /// C++: generated `SecureUnpackMsg`; the error is `FailedMsgOn()`.")
		lines.append("    pub fn unpack(u: &mut Unpacker) -> Result<Self, &'static str> {")
		lines.append("        let mut s = Self::default();")
		for acc, var in msg_slots(m):
			if type(var) in string_flags:
				lines.append(f"        s.{acc} = u.get_string({string_flags[type(var)]});")
			elif var.default is not None:
				lines.append(f"        s.{acc} = u.get_int_or_default({evaluate(var.default)});")
			else:
				lines.append(f"        s.{acc} = u.get_int();")
		lines.append("        let mut failed_on = None;")
		for acc, var in msg_slots(m):
			if isinstance(var, NetIntRange):
				lines.append(f"        if failed_on.is_none() && (s.{acc} < {evaluate(var.min)} || s.{acc} > {evaluate(var.max)}) {{ failed_on = Some(\"{var.name}\"); }}")
		lines.append("        if u.error() { failed_on = Some(\"(unpack error)\"); }")
		lines.append("        match failed_on { Some(f) => Err(f), None => Ok(s) }")
		lines.append("    }")
		lines.append("}")
		lines.append("")

	lines.append("/// Any game message. C++ dispatches on the id from `UnpackMessageId`.")
	lines.append("#[derive(Clone, Debug, PartialEq, Eq)]")
	lines.append("pub enum GameMsg {")
	for m in messages:
		n = type_name(m.name)
		lines.append(f"    {n}(Msg{n}),")
	lines.append("}")
	lines.append("/// C++: generated `CNetObjHandler::SecureUnpackMsg`.")
	lines.append("pub fn unpack_game_msg(id: i32, u: &mut Unpacker) -> Result<GameMsg, &'static str> {")
	lines.append("    match id {")
	for m in messages:
		n = type_name(m.name)
		lines.append(f"        {m.enum_name} => Msg{n}::unpack(u).map(GameMsg::{n}),")
	lines.append("        _ => Err(\"(type out of range)\"),")
	lines.append("    }")
	lines.append("}")
	lines.append("")

	# --- system ex messages (engine/shared/protocol_ex_msgs.h) ---
	with open(os.path.join(ROOT, "src", "engine", "shared", "protocol_ex_msgs.h"), encoding="utf-8") as f:
		sys_msgs = re.findall(r'^UUID\((\w+), "([^"]+)"\)', f.read(), re.M)
	lines.append("/// Ids for system messages sent as UUIDs; local to this client, never sent.")
	lines.append("pub const OFFSET_EX_SYSMSG: i32 = 0x30000;")
	for i, (ident, name) in enumerate(sys_msgs):
		lines.append(f"/// `{name}`, C++: `src/engine/shared/protocol_ex_msgs.h`.")
		lines.append(f"pub const {ident}: i32 = OFFSET_EX_SYSMSG + {i};")
	lines.append("/// (id, name, uuid) of every system ex message.")
	lines.append("pub static SYS_EX_MSGS: &[(i32, &str, [u8; 16])] = &[")
	for ident, name in sys_msgs:
		lines.append(f"    ({ident}, \"{name}\", {rust_bytes(calculate_uuid(name))}),")
	lines.append("];")

	return "\n".join(lines) + "\n"


def main():
	with open(OUT, "w", encoding="utf-8", newline="\n") as f:
		f.write(gen())
	subprocess.run(["rustfmt", "--edition", "2024", OUT], check=True)
	print(f"wrote {OUT}")


if __name__ == "__main__":
	main()
